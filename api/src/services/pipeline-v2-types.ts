/**
 * A single atomic step in the execution plan.
 * Each step is executed sequentially, commits on success.
 */
export interface PlannedStepV2 {
  /** Step index (0-based) */
  index: number;

  /** Short title describing the step */
  title: string;

  /** Detailed description of what needs to be done */
  description: string;

  /** Worker persona to use for this step */
  persona: WorkerPersona;

  /** How to verify this step completed successfully */
  verificationType: VerificationType;

  /** Specific verification instructions for the worker */
  verificationInstructions: string;

  /** Files this step will create or modify (max 3 for focus) */
  targetFiles: string[];

  /**
   * Files to read for context/patterns (not modified).
   *
   * Supports glob patterns for files that may not exist at planning time:
   * - Exact paths: "src/auth/Login.tsx"
   * - Wildcards: "src/**\/auth*.ts"
   * - Descriptions: "[the main auth module]"
   *
   * The Runner resolves these to actual paths before step execution.
   * If a pattern matches nothing, the agent will be instructed to find
   * the file itself using the description.
   */
  referenceFiles?: string[];

  /** Estimated complexity (1-3 scale) */
  estimatedComplexity?: 1 | 2 | 3;

  /** Timeout for this step in minutes (default: 15) */
  timeoutMinutes?: number;
}

/**
 * Default timeout per step in minutes
 */
export const DEFAULT_STEP_TIMEOUT_MINUTES = 15;

/**
 * Get effective timeout for a step
 */
export function getStepTimeout(step: PlannedStepV2): number {
  return (step.timeoutMinutes ?? DEFAULT_STEP_TIMEOUT_MINUTES) * 60 * 1000;
}

