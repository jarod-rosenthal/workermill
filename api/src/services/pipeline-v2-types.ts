// REWIND THRESHOLDS & COMMANDS
// ============================================================================

/**
 * Rewind threshold configuration
 * If exceeded, escalate to human instead of automatic rewind
 */
export const REWIND_THRESHOLDS = {
  /** Max steps to rewind before escalating */
  maxStepsToRewind: 2,
  /** Max percentage of completed steps to rewind */
  maxPercentageToRewind: 0.2,
  /** Max retries per step before considering rewind */
  maxRetriesPerStep: 3,
};

/**
 * Git command for rewind operations.
 *
 * CRITICAL: Must use both `git reset --hard` AND `git clean -fd`
 *
 * - `git reset --hard` moves HEAD and resets tracked files
 * - `git clean -fd` removes untracked files/directories created by the failed step
 *
 * Without git clean, "ghost files" from failed steps can confuse subsequent attempts.
 */
export const REWIND_GIT_COMMAND = (commitHash: string) =>
  `git reset --hard ${commitHash} && git clean -fd`;

/**
 * Git command for fresh start (no previous commits)
 */
export const FRESH_START_GIT_COMMAND = "git clean -fd";

