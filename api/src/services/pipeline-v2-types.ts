// REFERENCE FILE RESOLUTION
// ============================================================================

/**
 * Reference file resolution happens in the WORKER, not the API.
 *
 * Why: The API doesn't have access to the cloned repo filesystem.
 * The worker runs the following resolution logic before step execution:
 *
 * 1. For exact paths: verify file exists, add to resolved list
 * 2. For glob patterns: expand using fast-glob, add matches to resolved list
 * 3. For descriptions: add to unresolved instructions for agent to find
 *
 * The worker passes both `resolvedReferenceFiles` (actual paths) and
 * `unresolvedReferenceInstructions` (agent search tasks) to Claude.
 */

/**
 * Classify a reference file entry as exact path, glob pattern, or description.
 */
export function classifyReferenceFile(ref: string): "exact" | "glob" | "description" {
  // Descriptions are wrapped in brackets: [the main auth module]
  if (ref.startsWith("[") && ref.endsWith("]")) {
    return "description";
  }
  // Glob patterns contain wildcards
  if (ref.includes("*") || ref.includes("?") || ref.includes("{")) {
    return "glob";
  }
  // Otherwise it's an exact path
  return "exact";
}

/**
 * Resolved reference file with metadata about how it was resolved.
 */
export interface ResolvedReferenceFile {
  /** Original pattern/path from the plan */
  original: string;
  /** How it was classified */
  type: "exact" | "glob" | "description";
  /** Resolved file path(s), or null if unresolved */
  resolved: string[] | null;
  /** If unresolved, instruction for the agent */
  instruction?: string;
}

/**
 * Result of reference file resolution.
 */
export interface ReferenceFileResolution {
  /** Successfully resolved file paths */
  resolvedPaths: string[];
  /** Unresolved patterns with instructions for the agent */
  unresolvedInstructions: string[];
  /** Full resolution details for logging */
  details: ResolvedReferenceFile[];
}

/**
 * Build agent instructions for unresolved reference files.
 * Called when a pattern/description couldn't be resolved at runtime.
 */
export function buildUnresolvedInstruction(ref: string, type: "glob" | "description"): string {
  if (type === "description") {
    // Strip brackets from description
    const description = ref.slice(1, -1);
    return `Find the file matching this description: "${description}"`;
  }
  // Glob pattern
  return `Find files matching pattern: ${ref}`;
}
