/**
 * Check if a task is using V2 pipeline
 */
export function isV2Pipeline(task: { pipelineVersion?: string | null }): boolean {
  return task.pipelineVersion === "v2";
}

/**
 * Check if a rewind would exceed thresholds
 */
export function wouldExceedRewindThreshold(
  currentStepIndex: number,
  targetStepIndex: number,
  totalSteps: number,
): boolean {
  const stepsToRewind = currentStepIndex - targetStepIndex;

  // Check absolute step limit
  if (stepsToRewind > REWIND_THRESHOLDS.maxStepsToRewind) {
    return true;
  }

  // Check percentage limit (only if we have significant progress)
  if (totalSteps > 5) {
    const percentageToRewind = stepsToRewind / currentStepIndex;
    if (percentageToRewind > REWIND_THRESHOLDS.maxPercentageToRewind) {
      return true;
    }
  }

  return false;
}

/**
 * Get the template ID based on tech stack
 */
export function getTemplateId(techStack: TechStackV2): TechStackV2["templateId"] {
  // Explicit template ID takes precedence
  if (techStack.templateId) {
    return techStack.templateId;
  }

  // Infer from framework and language
  const { framework, language } = techStack;

  if (framework === "react" && techStack.buildTool === "vite" && language === "typescript") {
    return "react-vite-typescript";
  }
  if (framework === "fastapi" && language === "python") {
    return "fastapi-python";
  }
  if (framework === "express" && language === "typescript") {
    return "express-typescript";
  }
  if (framework === "nextjs" && language === "typescript") {
    return "nextjs-typescript";
  }

  // No matching template
  return null;
}

/**
 * Calculate overall pipeline progress percentage
 */
export function calculateProgress(currentStepIndex: number, totalSteps: number): number {
  if (totalSteps === 0) return 0;
  return Math.round((currentStepIndex / totalSteps) * 100);
}

